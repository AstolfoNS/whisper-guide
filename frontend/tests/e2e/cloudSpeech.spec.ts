import { useSyntheticMicrophone } from './syntheticMicrophone'
import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const screenshots = '../docs/screenshots/cloud-speech-2026-10-24'

test.beforeEach(async ({ page }) => { await useSyntheticMicrophone(page) })

test('configures independent cloud ASR and text LLM, aligns WS final and releases microphone on pause', async ({ page }) => {
  await page.goto('/settings/models')
  await page.getByRole('button', { name: '新建配置', exact: true }).click()
  await page.getByRole('textbox', { name: '配置名称', exact: true }).fill('双云流式语音验证')
  await page.getByLabel('STT Provider', { exact: true }).selectOption('cloud')
  await page.getByLabel('语音接口协议', { exact: true }).selectOption('volcengine-ws')
  await page.getByRole('button', { name: '填入推荐设置', exact: true }).click()
  await expect(page.getByLabel('语音 WebSocket Endpoint', { exact: true })).toHaveValue('wss://openspeech.bytedance.com/api/v3/sauc/bigmodel_async')
  await expect(page.getByLabel('语音服务 Resource ID', { exact: true })).toHaveValue('volc.seedasr.sauc.duration')
  await expect(page.locator('#profile-stt-app-id')).toHaveCount(0)
  await page.getByLabel('语音 WebSocket Endpoint', { exact: true }).fill('ws://127.0.0.1:8010/mock/asr/bigmodel_async')
  await page.getByLabel('语音服务 API Key', { exact: true }).fill('synthetic-browser-asr-key')
  await page.getByRole('checkbox', { name: /我同意将麦克风音频片段/ }).check()
  await page.getByLabel('对齐模式', { exact: true }).selectOption('hybrid')
  await page.getByLabel('Base URL', { exact: true }).fill('http://127.0.0.1:8010/mock')
  await page.getByLabel('API Key', { exact: true }).fill('synthetic-browser-llm-key')
  await page.getByLabel('模型名称', { exact: true }).fill('demo-fast-model')
  await page.getByRole('button', { name: '测试云端 STT', exact: true }).click()
  await expect(page.locator('.profile-test .n-alert')).toContainText('协议响应验证成功')
  await page.getByRole('button', { name: '测试大模型连通性', exact: true }).click()
  await expect(page.locator('.profile-test .n-alert')).toContainText('模型接口请求成功')
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByText('配置已保存，当前生效方案未改变。')).toBeVisible()
  await expect(page.getByLabel('语音服务 API Key', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
  await mkdir(screenshots, { recursive: true })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `${screenshots}/configuration.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '设为生效配置', exact: true }).click()
  await expect(page.getByText('配置已激活，下一次创建的会话将使用此版本。')).toBeVisible()
  const profile = (await (await page.request.get('/api/settings/model-configs')).json()).configs.find((item: { name: string }) => item.name === '双云流式语音验证')
  await page.getByRole('link', { name: '工作台', exact: true }).click()
  await page.getByLabel('上传讲稿', { exact: false }).setInputFiles({ name: '双云识别.txt', mimeType: 'text/plain', buffer: Buffer.from('大家好，今天验证双云识别。') })
  await page.getByRole('button', { name: '开始演讲', exact: true }).click()
  await expect(page.getByRole('region', { name: '实时语音识别', exact: true })).toContainText('大甲好')
  await expect(page.getByRole('region', { name: '实时语音识别', exact: true })).toContainText('final')
  await expect(page.getByRole('region', { name: '讲稿匹配', exact: true })).toContainText('大家好')
  await expect(page.locator('.reading-cursor')).toHaveText('好')
  await page.getByRole('button', { name: '暂停演讲', exact: true }).click()
  await expect(page.getByRole('button', { name: '继续演讲', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '结束', exact: true }).click()
  await expect(page.getByText('已结束', { exact: true })).toBeVisible()
  expect((await page.request.post('/api/settings/model-configs/local-default/activate')).ok()).toBe(true)
  expect((await page.request.delete(`/api/settings/model-configs/${profile.id}`)).ok()).toBe(true)
})

test('an unavailable cloud credential falls back to local without pausing the session', async ({ page }) => {
  const created = await page.request.post('/api/settings/model-configs', { data: { name: '回退验证', settings: {
    stt_provider: 'cloud', cloud_opt_in: true, cloud_stt_protocol: 'volcengine-ws', cloud_stt_auth_mode: 'api-key',
    cloud_stt_resource_id: 'volc.seedasr.sauc.duration', cloud_stt_endpoint: 'ws://127.0.0.1:8010/mock/asr/bigmodel_async',
    cloud_stt_access_token: 'synthetic-invalid-credential',
  } } })
  expect(created.status()).toBe(201)
  const profile = await created.json()
  expect((await page.request.post(`/api/settings/model-configs/${profile.id}/activate`)).ok()).toBe(true)
  await page.goto('/studio')
  await page.getByLabel('上传讲稿', { exact: false }).setInputFiles({ name: '回退讲稿.txt', mimeType: 'text/plain', buffer: Buffer.from('大家好，继续本地识别。') })
  await page.getByRole('button', { name: '开始演讲', exact: true }).click()
  await expect(page.getByRole('button', { name: '打开服务诊断', exact: true })).toContainText('识别已回退本地')
  await expect(page.getByRole('button', { name: '暂停演讲', exact: true })).toBeVisible()
  await expect(page.locator('.reading-cursor')).toHaveText('好')
  await page.getByRole('button', { name: '打开服务诊断', exact: true }).click()
  await expect(page.getByText('云端识别已回退本地', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '结束', exact: true }).click()
  await expect(page.getByText('已结束', { exact: true })).toBeVisible()
  expect((await page.request.post('/api/settings/model-configs/local-default/activate')).ok()).toBe(true)
  expect((await page.request.delete(`/api/settings/model-configs/${profile.id}`)).ok()).toBe(true)
})
