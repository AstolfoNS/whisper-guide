test('narrow workspace keeps keyboard navigation and no horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/studio')
  await expect(page.getByRole('heading', { name: '演讲工作台' })).toBeFocused()
  const skip = page.getByRole('link', { name: '跳到主要内容' })
  for (let index = 0; index < 10 && !await skip.evaluate(element => element === document.activeElement); index++) await page.keyboard.press('Shift+Tab')
  await expect(skip).toBeFocused()
  await page.getByRole('button', { name: '讲稿库', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('radio').first().check()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await page.screenshot({ path: `${screenshots}/studio-mobile.png`, fullPage: true, animations: 'disabled' })
})


