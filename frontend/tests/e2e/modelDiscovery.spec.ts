import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const screenshots = '../docs/screenshots/model-discovery-2026-10-24'

test('discovers draft models, searches and selects, then reuses a saved key without exposing it', async ({ page }) => {
  await page.goto('/settings/models')
  await page.getByRole('button', { name: '新建配置', exact: true }).click()
  await page.getByRole('textbox', { name: '配置名称', exact: true }).fill('模型发现浏览器验证')
  await expect(page.getByLabel('对齐模式', { exact: true })).toHaveValue('off')
  await expect(page.getByLabel('模型名称', { exact: true })).toHaveValue('')
  await page.getByLabel('Base URL', { exact: true }).fill('http://127.0.0.1:8010/mock')
  await page.getByLabel('API Key', { exact: true }).fill('synthetic-browser-discovery-key')
  const before = await (await page.request.get('/api/settings/model-configs')).json()
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/settings/model-configs/discover-models'))
  await page.getByRole('button', { name: '获取模型列表', exact: true }).click()
  const response = await responsePromise
  expect(response.status()).toBe(200)
  const result = await response.json()
  expect(result.models.map((model: { id: string }) => model.id)).toEqual(['demo-accurate-model', 'demo-fast-model'])
  expect(JSON.stringify(result)).not.toContain('synthetic-browser-discovery-key')
  await expect(page.getByLabel('从模型列表选择', { exact: true })).toBeVisible()
  await expect(page.getByLabel('模型名称', { exact: true })).toHaveValue('')
  await page.getByLabel('筛选模型', { exact: true }).fill('快速')
  await expect(page.locator('#profile-discovered-model option')).toHaveCount(2)
  await page.getByLabel('从模型列表选择', { exact: true }).selectOption('demo-fast-model')
  await expect(page.getByLabel('模型名称', { exact: true })).toHaveValue('demo-fast-model')
  const after = await (await page.request.get('/api/settings/model-configs')).json()
  expect(after).toEqual(before)
  await page.getByLabel('对齐模式', { exact: true }).selectOption('fallback')
  await page.getByRole('button', { name: '测试大模型连通性', exact: true }).click()
  await expect(page.getByText('模型接口请求成功。')).toBeVisible()
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByText('配置已保存，当前生效方案未改变。')).toBeVisible()
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('API Key', { exact: true })).toHaveAttribute('placeholder', '已保存，留空保留')
  const requestPromise = page.waitForRequest(request => request.url().endsWith('/api/settings/model-configs/discover-models'))
  await page.getByRole('button', { name: '获取模型列表', exact: true }).click()
  const request = await requestPromise
  expect(request.postDataJSON().settings).not.toHaveProperty('llm_api_key')
  expect(request.postDataJSON().id).toBeTruthy()
  await expect(page.getByLabel('从模型列表选择', { exact: true })).toBeVisible()
  await page.getByLabel('从模型列表选择', { exact: true }).selectOption('demo-accurate-model')
  await expect(page.getByLabel('模型名称', { exact: true })).toHaveValue('demo-accurate-model')
  await mkdir(screenshots, { recursive: true })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `${screenshots}/models.png`, fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `${screenshots}/models-mobile.png`, fullPage: true, animations: 'disabled' })
})

test('unsupported discovery shows its HTTP reason and retains manual model entry', async ({ page }) => {
  await page.goto('/settings/models')
  await page.getByRole('button', { name: '新建配置', exact: true }).click()
  await page.getByLabel('Base URL', { exact: true }).fill('http://127.0.0.1:8010/mock-unsupported')
  await page.getByRole('button', { name: '获取模型列表', exact: true }).click()
  await expect(page.getByRole('group', { name: '大模型语义对齐', exact: true }).getByRole('alert')).toContainText('HTTP 404')
  await expect(page.getByRole('group', { name: '大模型语义对齐', exact: true }).getByRole('alert')).toContainText('手动填写')
  await page.getByLabel('模型名称', { exact: true }).fill('ep-manual-model')
  await expect(page.getByLabel('模型名称', { exact: true })).toHaveValue('ep-manual-model')
})
